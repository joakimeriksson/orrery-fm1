"""Generate effects/fx_tables.h: integer tables for the local effects, so no floating point
runs on the device. Rerun after changing a law here:  python3 tools/gen_effect_tables.py"""
import math
from pathlib import Path

SR = 44100
OUT = Path(__file__).resolve().parents[1] / "effects" / "fx_tables.h"
# Cutoff units: f = 20 Hz * 2^(v / 100), v = 0..1000 (100 per octave). One entry per 10 units.
g = []
for i in range(101):
    f = min(20.0 * 2.0 ** (i * 10 / 100.0), 0.49 * SR)
    g.append(round(math.tan(math.pi * f / SR) * (1 << 24)))
lines = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* Generated by tools/gen_effect_tables.py; do not edit. */",
         "#ifndef MD_FX_TABLES_H", "#define MD_FX_TABLES_H", "#include <stdint.h>", "",
         "/* tan(pi f / 44100) in Q24 for f = 20 Hz * 2^(v / 100), v = 0, 10, ... 1000 (capped at 0.49 fs) */",
         "static const int32_t MD_FX_TAN_Q24[101] = {"]
for i in range(0, 101, 6):
    lines.append("    " + ", ".join(str(x) for x in g[i:i + 6]) + ",")
lines += ["};", "#endif", ""]
OUT.write_text("\n".join(lines))
print("wrote", OUT)
