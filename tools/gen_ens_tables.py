#!/usr/bin/env python3
"""engines/ens_tables.h: the tables of the ENSEMBLE engine (engines/ens_engine.c), made from the same formulas as
Felucca-Engines' tools/gen_engine_tables.py (MIT) and Caravel's tools/gen_tables.py (GPL-3.0-only), so the port
computes what the original does:  python3 tools/gen_ens_tables.py engines/ens_tables.h"""
import math
import sys
from pathlib import Path

FS = 44100
CTL = 32


def arr(name, ctype, vals, per=12):
    out = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def main(path):
    L = ["/* SPDX-License-Identifier: GPL-3.0-only */",
         "/* generated by tools/gen_ens_tables.py: the ENSEMBLE engine's tables (engines/ens_engine.c) */",
         "#ifndef ENS_TABLES_H", "#define ENS_TABLES_H", "#include <stdint.h>",
         f"#define ENS_FS {FS}", f"#define ENS_CTL {CTL}", ""]
    L += ["/* sine, 1025 points (the last is the first again) */"]
    L += arr("ENS_SINE", "int16_t", [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)])
    L += ["/* the phase increment of each MIDI note: 440 Hz * 2^((n - 69) / 12) */"]
    L += arr("ENS_NOTE_INC", "uint32_t",
             [min(int(440.0 * 2 ** ((n - 69) / 12) / FS * 2 ** 32), 0x7FFFFFFF) for n in range(128)], 8)
    cut = [30.0 * ((16000 / 30) ** (v / 127)) for v in range(128)]
    L += ["/* the trapezoidal SVF's g = tan(pi fc / FS) in Q12 for the cutoff indices 0..127 (30 Hz .. 16 kHz) */"]
    L += arr("ENS_SVF_G", "uint16_t", [int(4096 * math.tan(math.pi * min(f, 0.45 * FS) / FS)) for f in cut])
    L += ["/* tanh(i / 128) * 32767, i = 0..256 */"]
    L += arr("ENS_TANH", "int16_t", [int(32767 * math.tanh(i / 256 * 2)) for i in range(257)])
    ms = [1.0 * (10000 ** (v / 127)) for v in range(128)]
    L += ["/* the envelope times 1 ms .. 10 s (exponential in the value 0..127): the attack's step a control tick (Q24),",
          " * and the decay's and release's coefficient (Q16, about 99 % of the way after the time) */"]
    L += arr("ENS_ENV_LIN", "uint32_t", [max(1, int((1 << 24) * CTL / (m * FS / 1000))) for m in ms], 8)
    L += arr("ENS_ENV_EXP", "uint16_t",
             [max(1, min(65535, int(65536 * (1 - math.exp(-CTL / (m / 1000 / 4.6 * FS)))))) for m in ms])
    L += ["#endif"]
    Path(path).write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "engines/ens_tables.h")
